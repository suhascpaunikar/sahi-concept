#!/usr/bin/env python3
"""Turn the Kite 1-minute CSVs in this folder into ../src/data.js for the prototype.

Each series becomes flat arrays (o, h, l, c, and v and oi for options) with one slot per
trading minute, counted from 9:15 am on the first trading day. Missing minutes are null.
Option bars at or after 3:30 pm are left out: the chart's session is 9:15 am to 3:30 pm,
the same as the index.

Usage: python3 build_data.py   (run from anywhere)
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'data.js')
OPEN, SESSION = 9 * 60 + 15, 375
FILES = {
    'NIFTY': ('nifty50_1min.csv', False),
    'CE-22500-2026-10-19': ('nifty_26O1922500CE_1min.csv', True),
    'PE-22500-2026-10-19': ('nifty_26O1922500PE_1min.csv', True),
}


def read(name):
    rows = []
    with open(os.path.join(HERE, name), newline='') as f:
        for r in csv.DictReader(f):
            day, hm = r['datetime'].split(' ')
            h, m, _ = hm.split(':')
            rows.append((day, int(h) * 60 + int(m) - OPEN, r))
    return rows


series_rows = {k: read(f) for k, (f, _) in FILES.items()}
days = sorted({d for d, _, _ in series_rows['NIFTY']})
day_index = {d: i for i, d in enumerate(days)}

out = {}
for key, (_, is_option) in FILES.items():
    cols = ['o', 'h', 'l', 'c'] + (['v', 'oi'] if is_option else [])
    arr = {c: [] for c in cols}
    last = -1
    for day, minute, r in series_rows[key]:
        if day not in day_index or not 0 <= minute < SESSION:
            continue
        i = day_index[day] * SESSION + minute
        for c in cols:
            a = arr[c]
            while len(a) <= i:
                a.append(None)
        arr['o'][i] = round(float(r['open']), 2)
        arr['h'][i] = round(float(r['high']), 2)
        arr['l'][i] = round(float(r['low']), 2)
        arr['c'][i] = round(float(r['close']), 2)
        if is_option:
            arr['v'][i] = int(float(r['volume']))
            arr['oi'][i] = int(float(r['oi']))
        last = max(last, i)
    out[key] = arr
    print(f'{key}: {sum(v is not None for v in arr["c"])} minutes, last slot {last}')

data = {
    'source': 'Zerodha Kite (Kite MCP), 1-minute candles pulled on 14 Oct 2026; see data/HANDOVER.md',
    'days': days,
    'series': out,
}
with open(OUT, 'w') as f:
    f.write('// Generated by prototype/payoff/data/build_data.py from the Kite CSVs in data/. Do not edit by hand.\n')
    f.write('const RealData = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    f.write("if (typeof module !== 'undefined') module.exports = RealData;\n")
print('wrote', os.path.relpath(OUT, HERE), os.path.getsize(OUT), 'bytes')
